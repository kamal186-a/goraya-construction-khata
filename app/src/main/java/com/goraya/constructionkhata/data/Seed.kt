    suspend fun ensure(db: AppDatabase) {
        val dao = db.dao()
        if (dao.categoryCount() > 0) return
        db.withTransaction {
            var co = 0
            for (c in catalog) {
                val cid = dao.saveCategory(Category(name = c.name, code = c.code, sortOrder = co++))
                var so = 0
                for ((subName, items) in c.subs) {
                    val sid = dao.saveSub(SubCategory(categoryId = cid, name = subName, sortOrder = so++))
                    items.forEachIndexed { i, n -> dao.saveItem(Item(subCategoryId = sid, name = n, sortOrder = i)) }
                }
            }
            locations.forEachIndexed { i, n -> dao.saveLocation(Location(name = n, sortOrder = i)) }
            dao.saveSetting(Setting("project_name", "میرا گھر"))
        }
    }
